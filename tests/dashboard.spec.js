const {test,expect}=require('@playwright/test');
test('real data, scopes, filters, sorting and exports',async({page})=>{
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto('/');
  await expect(page.locator('#model-table tbody tr')).toHaveCount(32);
  await expect(page.locator('#route-cards .route-card')).toHaveCount(4);
  await expect(page.locator('#routing-table tbody tr')).toHaveCount(28);
  await expect(page.locator('#error')).toBeHidden();
  await page.locator('#model-dataset').selectOption('terminal');
  await expect(page.locator('#model-table tbody tr')).toHaveCount(4);
  await expect(page.locator('#model-table tbody')).toContainText('89');
  await page.locator('[data-scope=cohort]').click();
  await expect(page.locator('#model-table tbody')).toContainText('没有符合');
  await page.locator('#model-dataset').selectOption('science');
  await expect(page.locator('#model-table tbody tr')).toHaveCount(4);
  await expect(page.locator('#model-table tbody')).toContainText('/ 81');
  await page.locator('#model-search').fill('qwen');
  await expect(page.locator('#model-table tbody tr')).toHaveCount(1);
  await page.locator('#model-search').clear();
  await page.locator('#model-metric').selectOption('mean_output_tokens');
  await page.locator('[data-model-sort=accuracy]').click();
  const accuracy=await page.locator('#model-table tbody td:nth-child(2)').allTextContents();
  expect(parseFloat(accuracy[0])).toBeGreaterThanOrEqual(parseFloat(accuracy.at(-1)));
  await page.locator('#routing-dataset').selectOption('ds1000');
  await expect(page.locator('#routing-table tbody tr')).toHaveCount(4);
  for(const row of await page.locator('.selection-row').allTextContents())expect(row).toContain('1,000 次');
  await page.locator('#routing-dataset').selectOption('all');
  await expect(page.locator('.route-card.winner')).toContainText('KNN');
  const csv=await page.request.get('/assets/models.csv');expect(csv.ok()).toBeTruthy();expect(await csv.text()).toContain('mean_total_tokens');
  const width=await page.evaluate(()=>({scroll:document.documentElement.scrollWidth,view:innerWidth}));
  expect(width.scroll).toBeLessThanOrEqual(width.view+1);
  expect(errors).toEqual([]);
  await page.locator('[data-scope=formal]').click();await page.locator('#model-dataset').selectOption('all');await page.locator('#model-metric').selectOption('accuracy');
  await page.screenshot({path:`test-results/dashboard-${test.info().project.name}.png`,fullPage:true});
});
test('network errors are visible and recoverable',async({page})=>{
  await page.route('**/assets/data.json*',r=>r.fulfill({status:503,body:'unavailable'}));
  await page.goto('/');await expect(page.locator('#error')).toBeVisible();
  await page.unroute('**/assets/data.json*');await page.locator('#refresh').click();
  await expect(page.locator('#error')).toBeHidden();await expect(page.locator('#model-table tbody tr')).toHaveCount(32);
});
